def _span(text: str, phrase: str, value: str) -> tuple[int, int, str]:
    """Expected span: the phrase must be found verbatim and span the whole phrase."""
    start = text.index(phrase)
    return start, start + len(phrase), value


def _expected(text: str, parts: list[tuple[str, str]]) -> list[tuple[int, int, str]]:
    return [_span(text, phrase, value) for phrase, value in parts]


