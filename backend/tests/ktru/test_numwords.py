@pytest.mark.parametrize(("text", "parts"), CASES)
def test_spans(text: str, parts: list[tuple[str, str]]) -> None:
    assert spans(text) == _expected(text, parts)


def test_required_offsets_are_original_character_offsets() -> None:
    assert spans("Стол высота семь пять сантиметров") == [(12, 16, "7"), (17, 21, "5")]
    assert spans("массой половина килограмма") == [(7, 15, "0.5")]
    assert spans("семь запятая пять") == [(0, 17, "7.5")]
    assert spans("две целых пять десятых") == [(0, 22, "2.5")]
    assert spans("семь пять") == [(0, 4, "7"), (5, 9, "5")]
    assert spans("трёхсот") == [(0, 7, "300")]


@pytest.mark.parametrize(
    "text",
    [
        "",
        "стол",
        "Стол",
        "семья",
        "остановка",
        "полка",
        "полотно",
        "пол-литра",
        "тысячелетие",
        "стотысячный",
        "десятилетие",
        "Mass 7,5 kg",
    ],
)
def test_no_match_inside_other_words(text: str) -> None:
    assert spans(text) == []


def test_spans_are_sorted_and_do_not_overlap() -> None:
    text = "Длина сто двадцать пять или семь запятая пять сантиметров"
    result = spans(text)
    assert [value for *_, value in result] == ["125", "7.5"]
    assert all(a < b <= c < d for (a, b, _), (c, d, _) in zip(result, result[1:], strict=False))
    for start, end, _ in result:
        assert text[start:end] in {"сто двадцать пять", "семь запятая пять"}
