"""Generate frontend wire types from Pydantic JSON Schema; --check detects drift."""

import argparse
import json
import sys
from pathlib import Path

from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from src.ktru import contracts as C  # noqa: E402


def typescript(schema: dict, *, wire_required=False) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(typescript(item) for item in schema[union])
    kind = schema.get("type")
    if kind == "array":
        return f"({typescript(schema['items'])})[]"
    if kind == "object":
        properties = schema.get("properties")
        if properties is None:
            additional = schema.get("additionalProperties", {})
            return f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
        required = set(properties) if wire_required else set(schema.get("required", []))
        # Discriminated request unions require the tag even when its model has a default.
        required.update(key for key, value in properties.items() if "const" in value)
        lines = [f"  {key}{'' if key in required else '?'}: {typescript(value)}" for key, value in properties.items()]
        return "{\n" + "\n".join(lines) + "\n}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(
        str(kind), "unknown")


def generate() -> str:
    exports = [f"export const MAX_TEXT = {C.MAX_TEXT}", f"export const MAX_SPLIT_TEXT = {C.MAX_SPLIT_TEXT}"]
    for name, model in vars(C).items():
        if isinstance(model, type) and issubclass(model, C.Model) and model is not C.Model:
            schema = model.model_json_schema()
            # Pydantic serializes defaults on responses. Requests keep optional defaulted fields.
            wire_required = not name.endswith(("Request", "Patch"))
            exports.append(f"export type {name} = {typescript(schema, wire_required=wire_required)}")
    for name in ("Source", "Operator", "Polarity", "Origin", "Extractor", "SubjectKind", "Value", "Evidence"):
        exports.append(f"export type {name} = {typescript(TypeAdapter(getattr(C, name)).json_schema())}")
    exports.extend(["export type Readiness = CardState['readiness']", "export type FieldStatus = CardField['status']",
                    "export type ExampleDomain = Example['domain']", "export type EditPatch = EditRequest['patch']"])
    return "// Generated by backend/scripts/export_contract.py. Do not edit.\n\n" + "\n\n".join(exports) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "frontend/src/api/ktru.generated.ts"
    output = generate()
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit("Frontend contract is stale. Run backend/scripts/export_contract.py.")
    else:
        path.write_text(output)


if __name__ == "__main__":
    main()
